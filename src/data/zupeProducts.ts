export function doesCategoryMatch(productCategory: string, selectedCategory: string, dynamicCategories?: any[], product?: Partial<Product>): boolean {
  if (!selectedCategory || selectedCategory === "All Categories" || selectedCategory === "all" || selectedCategory === "All Products" || selectedCategory === "All") return true;
  const p = (productCategory || "").toLowerCase().trim();
  const s = selectedCategory.toLowerCase().trim();
  if (p === s) return true;
  if ((p === "gym supplementaries" || p === "gym supplements") && (s === "gym supplementaries" || s === "gym supplements")) return true;
  if ((p === "candy & chocolates" || p === "candy and chocolates") && (s === "candy & chocolates" || s === "candy and chocolates")) return true;
  if ((p === "dates & nuts" || p === "dates and nuts") && (s === "dates & nuts" || s === "dates and nuts")) return true;

  // The user's rule:
  // "in this dress images want out fits and apparels,but like spray,mackep set,lipstick,shoe like this want only in apparels"
  // When browsing "Apparels", dress images in "Outfits" should also appear in Apparels!
  if (s === "apparels" && p === "outfits") return true;

  return false;
}

export function doesSubcategoryMatch(product: Product, selectedSubcategory: string): boolean {
  if (!selectedSubcategory || selectedSubcategory === "All") return true;
  return product.subcategory?.toLowerCase() === selectedSubcategory.toLowerCase();
}
